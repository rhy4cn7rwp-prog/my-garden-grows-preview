test("temporary scale enables bulk display and normal educational checkout", () => {
  const s = G.initial();
  s.cash = 0;
  s.inventory.beans = 3;
  G.rentEquipment(s, "scale", "deferred");
  assert.deepEqual(G.addAllToDisplay(s).added, { beans: 3 });
  G.openMarket(s);
  G.newCustomer(s, "Maya");
  G.greet(s);
  s.basket = { ...s.customer.want };
  assert.throws(() => G.ring(s, 0));
  G.ring(s, 4);
  s.change = 1;
  G.finish(s);
  G.advanceCustomer(s);
  G.closeMarket(s);
  assert.equal(s.cash, 2);
  assert.equal(G.debtTotal(s), 0);
  assert.equal(s.marketChargesPaid, 2);
  assert.equal(s.owned.scale, 0);
});
test("market close deducts at most available earnings and never double-settles", () => {
  let s = G.initial();
  s.cash = 0;
  G.rentEquipment(s, "table", "deferred");
  s.marketPlayed = true;
  s.marketOpen = true;
  s.sales = 2;
  s.cash = 12;
  G.closeMarket(s);
  assert.equal(s.cash, 10);
  assert.equal(G.debtTotal(s), 1);
  assert.equal(s.marketChargesPaid, 2);
  G.closeMarket(s);
  assert.equal(s.cash, 10);
  s = G.recover(JSON.stringify(s));
  G.closeMarket(s);
  assert.equal(s.cash, 10);
  assert.equal(G.debtTotal(s), 1);
});
test("End Day settles fees before expiring equipment; old debt blocks new borrowing", () => {
  const s = G.initial();
  s.cash = 0;
  G.rentEquipment(s, "table", "deferred");
  G.rentEquipment(s, "scale", "deferred");
  s.marketPlayed = true;
  s.marketOpen = true;
  s.sales = 4;
  s.cash = 4;
  G.endDay(s);
  assert.equal(s.cash, 0);
  assert.equal(G.debtTotal(s), 1);
  assert.equal(G.hasEquipment(s, "scale"), false);
  assert.equal(s.standMode, "blanket");
  assert.throws(() => G.rentEquipment(s, "table", "deferred"));
  assert.equal(G.debtTotal(s), 1);
  s.inventory.carrot = 2;
  s.display.carrot = 2;
  G.openMarket(s);
  assert.equal(s.marketOpen, true);
});
test("unpaid no-sales rental carries without interest, cannot accumulate indefinitely", () => {
  const s = G.initial();
  s.cash = 0;
  G.rentEquipment(s, "table", "deferred");
  for (let i = 0; i < 25; i++) G.endDay(s);
  assert.equal(G.debtTotal(s), 3);
  assert.throws(() => G.rentEquipment(s, "bags", "deferred"));
  assert.equal(s.cash, 0);
  assert.equal(G.canReceiveSeedHelp(s), true);
});
test("voluntary debt payment respects available cash and permits later borrowing only after payoff", () => {
  const s = G.initial();
  s.cash = 0;
  G.rentEquipment(s, "scale", "deferred");
  G.endDay(s);
  s.cash = 0.5;
  assert.equal(G.payOutstanding(s), 0.5);
  assert.equal(G.debtTotal(s), 1.5);
  assert.equal(s.cash, 0);
  assert.throws(() => G.rentEquipment(s, "bags", "deferred"));
  s.cash = 2;
  assert.equal(G.payOutstanding(s), 1.5);
  assert.equal(s.cash, 0.5);
  assert.equal(G.debtTotal(s), 0);
  G.rentEquipment(s, "scale", "deferred");
  assert.equal(G.debtTotal(s), 2);
});
test("outstanding debt, active equipment, reservations and partial repayment survive save recovery", () => {
  const s = G.initial();
  s.cash = 0;
  s.seeds.tomato = 2;
  G.plan(s, 0, "tomato");
  G.rentEquipment(s, "table", "deferred");
  G.rentEquipment(s, "scale", "deferred");
  s.cash = 1;
  G.payOutstanding(s);
  const r = G.recover(JSON.stringify(s));
  assert.equal(G.debtTotal(r), 4);
  assert.equal(r.rentals.scale.payment, "deferred");
  assert.equal(G.hasEquipment(r, "scale"), true);
  assert.equal(G.availableSeeds(r, "tomato"), 1);
  assert.equal(r.cash, 0);
  assert.equal(r.goal, s.goal);
});
test("legacy paid tables migrate without charging or creating debt", () => {
  const s = G.initial();
  s.tableRented = true;
  s.standMode = "rental";
  delete s.rentals;
  delete s.equipmentDebt;
  delete s.marketSettled;
  delete s.rentalUpfrontPaid;
  delete s.marketChargesPaid;
  const r = G.recover(JSON.stringify(s));
  assert.equal(G.debtTotal(r), 0);
  assert.equal(r.rentals.table.payment, "legacy");
  assert.equal(r.cash, 50);
});
