const { test } = require("node:test");
const assert = require("node:assert/strict");
const G = require("../src/game.js");
test("seed reservations display immediately, survive reload, cancel and finalize exactly once", () => {
  let s = G.initial();
  s.seeds.tomato = 2;
  G.plan(s, 0, "tomato");
  G.plan(s, 1, "tomato");
  assert.equal(G.availableSeeds(s, "tomato"), 0);
  assert.throws(() => G.plan(s, 2, "tomato"));
  s = G.recover(JSON.stringify(s));
  assert.equal(G.availableSeeds(s, "tomato"), 0);
  assert.equal(Object.keys(s.plan).length, 2);
  G.cancelPlan(s, 1);
  assert.equal(G.availableSeeds(s, "tomato"), 1);
  G.plantPlan(s);
  assert.equal(s.seeds.tomato, 1);
  assert.equal(G.availableSeeds(s, "tomato"), 1);
  assert.throws(() => G.plantPlan(s));
});
test("invalid plans are dropped individually without resetting a saved farm", () => {
  const s = G.initial();
  s.cash = 12;
  s.seeds.carrot = 1;
  s.plan = { 0: "carrot", 1: "carrot", 99: "corn", bad: "carrot" };
  const r = G.recover(JSON.stringify(s));
  assert.equal(r.cash, 12);
  assert.deepEqual(r.plan, { 0: "carrot" });
  G.cancelAllPlans(r);
  assert.equal(G.availableSeeds(r, "carrot"), 1);
});
test("bulk harvest applies normal quality and finite repeat rules without duplication", () => {
  const s = G.initial();
  s.plots[0] = { id: "carrot", age: 3, left: 0, quality: 40, watered: false };
  s.plots[1] = { id: "beans", age: 3, left: 1, quality: 100, watered: true };
  s.plots[2] = { id: "corn", age: 2, left: 0, quality: 100, watered: false };
  const result = G.harvestAll(s);
  assert.deepEqual(result, { plots: 2, harvested: { carrot: 1, beans: 1 } });
  assert.equal(s.plots[0], null);
  assert.equal(s.plots[1].age, 0);
  assert.equal(s.plots[1].left, 0);
  assert.equal(s.plots[1].watered, false);
  assert.equal(s.plots[2].age, 2);
  assert.equal(G.harvestAll(s).plots, 0);
  assert.deepEqual(s.inventory, { carrot: 1, beans: 1 });
});
test("bulk display adds inventory once, reports scale requirement and never sells produce", () => {
  const s = G.initial();
  s.inventory = { carrot: 5, beans: 4 };
  s.display.carrot = 2;
  const r = G.addAllToDisplay(s);
  assert.deepEqual(r, { added: { carrot: 3 }, skipped: { beans: 4 } });
  assert.equal(s.cash, 50);
  assert.equal(s.inventory.carrot, 5);
  assert.deepEqual(G.addAllToDisplay(s).added, {});
  s.owned.scale = 1;
  assert.deepEqual(G.addAllToDisplay(s).added, { beans: 4 });
  s.customer = {};
  assert.throws(() => G.addAllToDisplay(s));
});

test("all rental prices are explicit; owned equipment cannot be rented or double-charged", () => {
  const s = G.initial();
  s.cash = 10;
  for (const id of ["table", "scale", "bags"])
    G.rentEquipment(s, id, "upfront");
  assert.equal(s.cash, 7.5);
  assert.equal(s.rentalUpfrontPaid, 2.5);
  assert.equal(G.hasEquipment(s, "scale"), true);
  assert.throws(() => G.rentEquipment(s, "scale", "upfront"));
  s.owned.bags = 1;
  assert.throws(() => G.rentEquipment(s, "bags", "deferred"));
});
test("deferred equipment requires explicit consent and unaffordability, capped at $6", () => {
  const s = G.initial();
  assert.throws(() => G.rentEquipment(s, "table", "deferred"));
  s.cash = 0;
  for (const id of ["table", "scale", "bags"])
    G.rentEquipment(s, id, "deferred");
  assert.equal(s.cash, 0);
  assert.equal(G.debtTotal(s), 6);
  assert.equal(s.rentalUpfrontPaid, 0);
  assert.throws(() => G.rentEquipment(s, "bags", "deferred"));
  assert.equal(G.debtTotal(s), 6);
});
